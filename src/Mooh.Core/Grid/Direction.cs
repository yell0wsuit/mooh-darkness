namespace Mooh.Core.Grid
{
    /// <summary>
    /// Identifies a cardinal direction on the world grid.
    /// </summary>
    public enum Direction
    {
        /// <summary>Moves one cell toward decreasing X coordinates.</summary>
        Left,

        /// <summary>Moves one cell toward decreasing Y coordinates.</summary>
        Up,

        /// <summary>Moves one cell toward increasing X coordinates.</summary>
        Right,

        /// <summary>Moves one cell toward increasing Y coordinates.</summary>
        Down,
    }
}
